/**
 * main.js
 * ----------------------------------------------------------------------------
 * Точка входа приложения. Подключается в HTML как:
 *   <script type="module" src="/JS/main.js"></script>
 *
 * Что делает:
 *   1. Импортирует все модули.
 *   2. Инициализирует их в правильном порядке.
 *   3. Связывает частицы с модалкой (пауза при открытии).
 *   4. Подключает тумблер фоновых эффектов (с сохранением в localStorage).
 *   5. Снимает класс .no-js с <html>, чтобы включить CSS-анимации.
 *
 * Порядок инициализации ВАЖЕН:
 *   • LazyLoad — первым: картинки начинают грузиться как можно раньше.
 *   • Particles — до модалки: modal.js ожидает контроллер частиц.
 *   • Modal — до Galleries: галереи зовут openModal() по клику.
 *   • EffectsToggle — после Particles: получает готовый контроллер.
 *   • ScrollAnim — последним: только добавляет класс .visible.
 *
 * Почему нет DOMContentLoaded:
 *   type="module" по умолчанию выполняется после парсинга HTML
 *   (defer-поведение), DOM гарантированно готов.
 * ----------------------------------------------------------------------------
 */

import { LazyLoadManager } from './modules/lazy-load.js';
import { initParticleAnimation, initEffectsToggle } from './modules/particles.js';
import { initModal, setParticlesController } from './modules/modal.js';
import { initGalleries } from './modules/galleries.js';
import { initScrollAnimations } from './modules/scroll-anim.js';

// ---------------------------------------------------------------------------
// 1. Ленивая загрузка изображений
// ---------------------------------------------------------------------------
// Запускаем первой: чем раньше начнётся загрузка, тем быстрее появятся фото.
// IntersectionObserver подхватит те, что уже во вьюпорте, остальные — по скроллу.
new LazyLoadManager();

// ---------------------------------------------------------------------------
// 2. Фоновая анимация частиц (canvas + пул)
// ---------------------------------------------------------------------------
// Возвращает API:
//   { start, stop, destroy, setEnabled, isEnabled }
//
// Внутри модуль сам проверяет:
//   • наличие #background-animation;
//   • prefers-reduced-motion (если включено — возвращает пустой API);
//   • состояние из localStorage (если пользователь выключал — не запускает).
const particlesFx = initParticleAnimation();

// ---------------------------------------------------------------------------
// 3. Модальное окно
// ---------------------------------------------------------------------------
// initModal() навешивает слушатели (Esc, стрелки, клик по фону, close).
// Вызывается ДО initGalleries(), потому что галереи будут звать openModal().
initModal();

// Передаём контроллер частиц в modal.js, чтобы он мог ставить
// анимацию на паузу, пока пользователь смотрит фото/видео.
// Это экономит батарею: rAF-цикл останавливается полностью.
setParticlesController( particlesFx );

// ---------------------------------------------------------------------------
// 4. Тумблер фоновых эффектов
// ---------------------------------------------------------------------------
// Кнопка в правом верхнем углу. Состояние сохраняется в localStorage.
// Синхронизирована с контроллером частиц: клик → setEnabled().
initEffectsToggle( particlesFx );

// ---------------------------------------------------------------------------
// 5. Галереи
// ---------------------------------------------------------------------------
// Кнопки ‹ ›, свайпы, клики по миниатюрам → openModal().
// Каждая галерея сама проверяет наличие нужных элементов.
initGalleries();

// ---------------------------------------------------------------------------
// 6. Анимация появления блоков при скролле
// ---------------------------------------------------------------------------
// Добавляет .visible к .content-block при попадании во вьюпорт.
// Идёт последней — не блокирует ничего критичного.
initScrollAnimations();

// ---------------------------------------------------------------------------
// 7. Снимаем .no-js
// ---------------------------------------------------------------------------
// В CSS есть правило .no-js .content-block { opacity: 1 } — fallback
// на случай, если JS не загрузился или упал. Раз мы дошли до этой строки,
// модули инициализированы успешно — можно включать анимации появления.
//
// Ставим в конец, чтобы если какой-то модуль выше бросит исключение,
// .no-js остался и контент всё равно был виден.
document.documentElement.classList.remove( 'no-js' );